function setLanguage(value) { language = value === "en" ? "en" : "zh"; }

function t(source, ...values) {
  const key = Array.isArray(source) ? source.reduce((text, part, index) => text + (index ? `{${index - 1}}` : "") + part, "") : source;
  const text = language === "en" && Object.hasOwn(english, key) ? english[key] : key;
  return values.length ? text.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match) : text;
}

