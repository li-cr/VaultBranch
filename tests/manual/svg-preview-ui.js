(async () => {
  if (app.vault.getName() !== "note_test") throw Error("Run only in note_test.");
  const p = app.plugins.plugins.vaultbranch;
  if (!p || [...p.editors.sessions.values()].some(s => s.dirty || s.saving)) throw Error("Save drafts first.");
  await p.diffNavigationTask; await p.refreshTask; p.refreshSoon?.cancel();
  const fs = require("node:fs/promises"), path = require("node:path"), os = require("node:os");
  const exec = require("node:util").promisify(require("node:child_process").execFile);
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vaultbranch-svg-"));
  const saved = { git: p.git, status: p.status, ready: p.ready, scheduleRefresh: p.scheduleRefresh, lastAutoRefresh: p.lastAutoRefresh, write: p.editors.write, settings: { ...p.settings } };
  const git = async (...args) => (await exec(saved.git.binary, args, { cwd: root, windowsHide: true })).stdout;
  const write = async (name, text) => { await fs.mkdir(path.dirname(path.join(root, name)), { recursive: true }); await fs.writeFile(path.join(root, name), text); };
  const svg = (color, width = 80, extra = "") => `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="60"><rect width="100%" height="100%" fill="${color}"/>${extra}</svg>\n`;
  const name = "Fig/deep/nested/icon.svg", base = svg("red"), staged = svg("green", 100), working = svg("blue", 120);
  const largeName = "Other/deep/nested/icon.svg", large = svg("red", 400, `<!--${"x".repeat(1100000)}-->`);
  const results = [], samples = [], fixtures = [{ path: name, bytes: Buffer.byteLength(working), lines: 2 }, { path: largeName, bytes: Buffer.byteLength(large), lines: 2 }];
  const check = (value, message) => { if (!value) throw Error(message); results.push(message); };
  const wait = async predicate => { const until = performance.now() + 15000; while (!predicate()) { if (performance.now() > until) throw Error("SVG UI timeout"); await new Promise(r => setTimeout(r, 10)); } };
  const frame = () => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)));
  const remote = require("electron").remote, web = remote.getCurrentWebContents();
  remote.getCurrentWindow().show(); remote.getCurrentWindow().focus();
  const click = async node => {
    node.scrollIntoView({ block: "center" });
    const rect = node.getBoundingClientRect(), point = { x: Math.round(rect.x + rect.width / 2), y: Math.round(rect.y + rect.height / 2), button: "left", clickCount: 1 };
    const event = new Promise((resolve, reject) => { const timer = setTimeout(() => { node.removeEventListener("click", done); reject(Error("SVG native click timeout")); }, 3000); const done = e => { clearTimeout(timer); resolve(e); }; node.addEventListener("click", done, { once: true }); });
    web.sendInputEvent({ type: "mouseDown", ...point }); web.sendInputEvent({ type: "mouseUp", ...point });
    check((await event).isTrusted, "SVG mode button receives a trusted native click");
  };
  let leaf, historyLeaf, server, release, pending;
  try {
    p.scheduleRefresh = () => {}; p.lastAutoRefresh = Date.now() + 3600000;
    p.settings.diffAutosave = false; p.settings.syntaxHighlighting = false;
    for (const open of app.workspace.getLeavesOfType("vaultbranch-diff")) await open.detach();
    await git("init", "-b", "main"); await git("config", "user.name", "SVG test"); await git("config", "user.email", "svg@example.invalid");
    await write(name, base); await write(largeName, large); await git("add", "."); await git("commit", "-m", "SVG base");
    const created = (await git("rev-parse", "HEAD")).trim();
    await write(name, staged); await git("add", name); await git("commit", "-m", "SVG history");
    const edited = (await git("rev-parse", "HEAD")).trim();
    await write(name, working); await git("add", name); await write(name, base);
    await write(largeName, large.replace('fill="red"', 'fill="blue"'));
    await write("broken.svg", "<svg><broken>"); await write("new.SVG", working);
    p.git = new saved.git.constructor(root, { binary: saved.git.binary }); await p.git.init(); p.ready = true; p.status = await p.git.status();
    const index = await git("write-tree");
    p.editors.write = async (filePath, expected, text) => {
      const actual = await fs.readFile(path.join(root, filePath), "utf8");
      if (actual !== expected) throw Error("External modification");
      await write(filePath, text);
    };
    const open = async (filePath = name, area = "unstaged", extra = {}) => {
      leaf = await p.openDiff({ ...(p.status.files.find(file => file.path === filePath) || { path: filePath, worktree: "M" }), ...extra }, area);
      return leaf.view;
    };
    let view = await open();
    const images = () => [...view.svg.previewEl.querySelectorAll("img")];
    check(view.svg.preview && !view.merge && view.session && images().length === 2, "Changed SVG defaults to decoded preview without creating CodeMirror");
    check(images()[0].naturalWidth === 120 && images()[1].naturalWidth === 80, "Changed preview compares index with worktree");
    check(view.svg.toggle.parentElement.classList.contains("vaultbranch-diff-description"), "mode switch sits at the right of the version-description row");
    const screenshot = async name => {
      const output = window.__vbReleaseOptions?.outputDir || window.__vbSvgOutputDir;
      if (output) await fs.writeFile(path.join(output, name + ".png"), (await web.capturePage()).toPNG());
    };
    await frame(); await screenshot("svg-preview");
    const toggle = async preview => { await click(view.svg.toggle); await wait(() => view.svg.preview === preview && !view.svg.switching); await frame(); };
    await toggle(false);
    check(!view.svg.sourceEl.hidden && view.merge.a.state.readOnly && !view.merge.b.state.readOnly, "source mode exposes a readonly index and editable worktree");
    await screenshot("svg-source");
    const merge = view.merge, position = merge.b.state.doc.toString().indexOf("red"), replacement = base.replace("red", "purple");
    merge.b.dispatch({ selection: { anchor: position } }); merge.b.focus();
    let trustedInput = false;
    merge.b.contentDOM.addEventListener("beforeinput", event => { trustedInput = event.isTrusted; }, { once: true });
    web.sendInputEvent({ type: "char", keyCode: "b" });
    await wait(() => view.session.draft.text === base.slice(0, position) + "b" + base.slice(position));
    check(trustedInput, "SVG source accepts trusted native keyboard input");
    web.sendInputEvent({ type: "keyDown", keyCode: "Z", modifiers: ["control"] }); web.sendInputEvent({ type: "keyUp", keyCode: "Z", modifiers: ["control"] });
    await wait(() => view.session.draft.text === base);
    merge.b.dispatch({ changes: { from: position, to: position + 3, insert: "purple" }, selection: { anchor: position + 6 } });
    const selection = merge.b.state.selection.main.anchor;
    await toggle(true);
    check(view.session.draft.text === replacement && await fs.readFile(path.join(root, name), "utf8") === base, "preview uses the unsaved draft without writing disk");
    check(images()[1].src.includes(Buffer.from(replacement).toString("base64")), "preview displays the edited SVG");
    await toggle(false);
    check(view.merge === merge && merge.b.state.selection.main.anchor === selection, "mode switches preserve editor instance and selection");
    merge.b.focus(); web.sendInputEvent({ type: "keyDown", keyCode: "Z", modifiers: ["control"] }); web.sendInputEvent({ type: "keyUp", keyCode: "Z", modifiers: ["control"] });
    await wait(() => view.session.draft.text === base);
    check(view.session.draft.text === base, "native Undo survives SVG mode switches");
    merge.b.dispatch({ changes: { from: position, to: position + 3, insert: "purple" } });
    await toggle(true); await view.saveEditor();
    check(await fs.readFile(path.join(root, name), "utf8") === replacement && !view.session.dirty, "manual save in preview saves the retained draft");
    await toggle(false); merge.b.dispatch({ changes: { from: position, to: position + 6, insert: "orange" } });
    await write(name, working); await view.session.sync();
    check(view.session.error && await view.saveEditor() === false && view.session.draft.text.includes("orange"), "external modifications block overwrite and preserve the SVG draft");
    await view.session.reload();
    await open(largeName); await open(name);
    check(view.svg.preview && !view.merge, "reopening a file starts in preview and releases the old editor");
    for (let n = 0; n < 5; n++) for (const filePath of [largeName, name]) {
      const start = performance.now(); view = await open(filePath); const readyMs = performance.now() - start;
      check(view.svg.preview && !view.merge && images().every(image => image.complete && image.naturalWidth), "mixed large/small nested SVG previews arrive fully decoded");
      samples.push({ path: filePath, readyMs });
    }
    view = await open(name, "staged");
    check(images()[0].naturalWidth === 100 && images()[1].naturalWidth === 120 && !view.session, "Staged SVG reads HEAD/index independently of disk");
    check(view.svg.toggle.parentElement.classList.contains("vaultbranch-diff-description"), "Staged uses the same version-description row for its mode switch");
    await frame(); await screenshot("svg-staged-preview");
    await toggle(false);
    check(view.merge.a.state.readOnly && view.merge.b.state.readOnly && !view.saveButton, "Staged source remains readonly");
    await screenshot("svg-staged-source");
    view = await open(name, "history", { commit: created });
    check(images().length === 1 && images()[0].naturalWidth === 80, "root commit SVG has no parent image");
    await toggle(false); check(view.merge.a.state.readOnly && view.merge.b.state.readOnly, "commit source remains readonly");
    view = await open(name, "history", { commit: edited });
    check(images()[0].naturalWidth === 80 && images()[1].naturalWidth === 100, "commit preview compares the actual parent and commit");
    historyLeaf = await p.openFileHistory(name);
    const historyView = historyLeaf.view;
    check(historyView.svg.preview && !historyView.merge, "file history also defaults to SVG preview");
    await frame(); await screenshot("svg-file-history");
    await historyView.svg.switchMode();
    check(historyView.merge.a.state.readOnly && historyView.merge.b.state.readOnly, "file-history source stays readonly");
    await historyView.selectCommit(historyView.commits.find(commit => commit.hash === created));
    check(historyView.svg.preview && !historyView.merge && historyView.svg.previewEl.querySelectorAll("img").length === 1, "history selection resets preview and cleans up the old source editor");
    await historyLeaf.detach(); historyLeaf = null;
    view = await open("broken.svg");
    check(view.svg.previewEl.querySelector(".is-error") && !view.merge, "invalid SVG keeps a source switch available");
    await toggle(false);
    view.merge.b.dispatch({ changes: { from: 0, to: view.merge.b.state.doc.length, insert: base } });
    await toggle(true); check(images().length === 1 && images()[0].naturalWidth === 80, "invalid SVG can be repaired in source and previewed without saving");
    await view.session.reload();
    view = await open("new.SVG"); check(images().length === 1, "new uppercase SVG has one image and an empty index");
    await write("limit.svg", svg("red", 80, `<!--${"x".repeat(2 * 1024 * 1024)}-->`));
    view = await open("limit.svg");
    check(!view.svg && view.contentEl.textContent.includes("2 MB"), "over-limit SVG retains the existing bounded text fallback");
    let requests = 0;
    server = require("node:http").createServer((req, res) => { requests++; res.end("blocked"); });
    await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
    const url = `http://127.0.0.1:${server.address().port}/external`;
    delete window.__vbSvgExecuted;
    await write("isolated.svg", svg("red", 80, `<script>globalThis.__vbSvgExecuted=true;fetch('${url}')</script><image href="${url}" width="10" height="10"/>`));
    view = await open("isolated.svg"); await frame();
    check(!window.__vbSvgExecuted && requests === 0 && !view.contentEl.querySelector("svg script"), "image-document previews execute no SVG scripts or external requests");
    await new Promise(resolve => server.close(resolve)); server = null;
    view = await open(name);
    const old = images(), read = view.readComparison;
    let started; const begin = new Promise(r => { started = r; }); const gate = new Promise(r => { release = r; }); let late;
    view.readComparison = async function (...args) { const result = await read.apply(this, args); if (args[0].path === largeName) { late = result; started(); await gate; } return result; };
    pending = p.openDiff(p.status.files.find(file => file.path === largeName), "unstaged"); await begin;
    check(old.every(image => image.getAttribute("src")) && view.contentEl.inert, "pending SVG reads retain the complete previous preview");
    await open(name); release(); await pending; pending = null; view.readComparison = read;
    check(view.file.path === name && !view.contentEl.inert, "late SVG results cannot overwrite a newer file");
    const removed = document.createElement("div"); late.svg.images.render(removed, ["old", "new"]);
    check([...removed.querySelectorAll("img")].every(image => !image.getAttribute("src")), "cancelled SVG previews release image sources");
    await fs.unlink(path.join(root, name));
    view = await open(name, "unstaged", { worktree: "D" });
    check(images().length === 1 && images()[0].naturalWidth === 120, "deleted SVG previews the index with an empty worktree");
    await toggle(false); check(view.merge.a.state.readOnly && view.merge.b.state.readOnly, "deleted SVG source is readonly");
    const last = images(); await leaf.detach(); leaf = null;
    check(last.every(image => !image.getAttribute("src")) && !p.editors.sessions.size && !p.editors.pending.size, "closing releases SVG sources and all retained sessions");
    view = await open(largeName);
    const closeRead = view.readComparison;
    let closeStarted, closeLoaded;
    const closing = new Promise(resolve => { closeStarted = resolve; });
    const closeGate = new Promise(resolve => { release = resolve; });
    view.readComparison = async function (...args) { closeLoaded = await closeRead.apply(this, args); closeStarted(); await closeGate; return closeLoaded; };
    pending = p.openDiff(p.status.files.find(file => file.path === largeName), "unstaged"); await closing;
    await leaf.detach(); leaf = null; release(); await pending; pending = null;
    const closedImages = document.createElement("div"); closeLoaded.svg.images.render(closedImages, ["old", "new"]);
    check([...closedImages.querySelectorAll("img")].every(image => !image.getAttribute("src")) && !p.editors.sessions.size && !p.editors.pending.size, "closing during an SVG read releases late images and sessions");
    check(await git("write-tree") === index, "SVG preview, source edits and history never change the staged index");
    check(!(window.__vaultbranchErrors || []).length, "no SVG runtime errors");
    return { results, fixtures, samples };
  } finally {
    release?.(); if (pending) await pending.catch(() => {});
    if (leaf) { await leaf.view.session?.reload(); await leaf.detach(); }
    if (historyLeaf) await historyLeaf.detach();
    if (server) await new Promise(r => server.close(r));
    p.editors.write = saved.write;
    p.git = saved.git; p.status = saved.status; p.ready = saved.ready; p.scheduleRefresh = saved.scheduleRefresh; p.lastAutoRefresh = saved.lastAutoRefresh;
    Object.assign(p.settings, saved.settings);
    await p.refresh(); await fs.rm(root, { recursive: true, force: true });
  }
})()
