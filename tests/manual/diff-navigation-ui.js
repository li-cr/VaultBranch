(async () => {
  if (app.vault.getName() !== "note_test") throw Error("Run only in the note_test vault.");
  const p = app.plugins.plugins.vaultbranch;
  const results = [], errors = [];
  const check = (value, label) => { if (!value) throw Error(label); results.push(label); };
  const onError = event => errors.push(event.message || String(event.reason));
  window.addEventListener("error", onError);
  window.addEventListener("unhandledrejection", onError);
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  const name = `vaultbranch-navigation-ui-${Date.now()}.md`;
  const base = Array.from({ length: 120 }, (_, n) => `line ${n}`).join("\n") + "\n";
  const edited = base.replace("line 20\n", "change 20\n").replace("line 60\n", "change 60\n").replace("line 100\n", "");
  const file = await app.vault.create(name, base);
  const saved = { navigation: p.settings.showDiffNavigation, collapse: p.settings.collapseUnchanged, autosave: p.settings.diffAutosave, language: p.settings.language };
  const scheduleRefresh = p.scheduleRefresh, lastAutoRefresh = p.lastAutoRefresh;
  let leaf, historyLeaf, root, original, staged = false;
  const controls = view => view.contentEl.querySelectorAll(".vaultbranch-diff-navigation button");
  const click = async (view, index) => { controls(view)[index].click(); await pause(90); };
  const key = (editor, value) => editor.contentDOM.dispatchEvent(new KeyboardEvent("keydown", { key: value, code: "Key" + value.toUpperCase(), ctrlKey: true, bubbles: true }));
  try {
    if (p.refreshTask) await p.refreshTask;
    p.refreshSoon?.cancel(); p.scheduleRefresh = () => {}; p.lastAutoRefresh = Date.now() + 3600000;
    await p.updateSetting("diffAutosave", false);
    await p.updateSetting("showDiffNavigation", true);
    await p.updateSetting("collapseUnchanged", true);
    await p.git.stage([name]);
    staged = true;
    const index = await p.git.run(["show", ":" + name]);
    await app.vault.modify(file, edited);
    leaf = await p.openDiff({ path: name, index: "A", worktree: "M" }, "unstaged");
    const view = leaf.view, merge = view.merge;
    check(controls(view).length === 2 && merge.chunks.length === 3, "editable diff displays two buttons for three native chunks");
    const expected = merge.chunks.map(chunk => chunk.fromB);
    await click(view, 1);
    check(merge.b.state.selection.main.head === expected[0], "down arrow selects first change from document start");
    await click(view, 1);
    check(merge.b.state.selection.main.head === expected[1], "down arrow selects next change");
    await click(view, 1);
    check(merge.b.state.selection.main.head === expected[2], "pure deletion remains a navigable chunk");
    await click(view, 1);
    check(merge.b.state.selection.main.head === expected[0], "native navigation wraps from last change to first");
    await click(view, 0);
    check(merge.b.state.selection.main.head === expected[2], "up arrow wraps from first change to last");
    merge.b.dispatch({ selection: { anchor: 0 }, changes: { from: 0, insert: "unsaved input\n" } });
    const text = merge.b.state.doc.toString(), selection = merge.b.state.selection.main.head;
    await p.updateSetting("showDiffNavigation", false);
    check(controls(view).length === 0 && view.merge === merge, "setting hides controls without rebuilding editor");
    await p.updateSetting("showDiffNavigation", true);
    check(controls(view).length === 2 && merge.b.state.doc.toString() === text && merge.b.state.selection.main.head === selection, "enabling controls preserves draft and selection");
    merge.b.focus(); key(merge.b, "z");
    check(merge.b.state.doc.toString() === edited, "Ctrl+Z survives navigation setting changes");
    await p.updateSetting("language", "zh");
    check(controls(view)[0].getAttribute("aria-label") === "上一处差异" && view.merge === merge, "Chinese tooltips update without losing editable editor");
    await p.updateSetting("language", "en");
    check(controls(view)[1].getAttribute("aria-label") === "Next change", "English tooltip is translated");
    check(await app.vault.read(file) === edited && await p.git.run(["show", ":" + name]) === index, "navigation does not save drafts or modify the index");
    await view.session.reload();
    merge.b.dispatch({ changes: { from: 0, to: merge.b.state.doc.length, insert: base } });
    check([...controls(view)].every(button => button.disabled), "buttons disable when editing removes all differences");
    key(merge.b, "z");
    check([...controls(view)].every(button => !button.disabled), "undo re-enables navigation when changes return");
    await view.session.reload();
    await p.openDiff({ path: name, index: "A", worktree: "M" }, "staged");
    check(controls(view).length === 2 && view.merge.b.state.readOnly, "staged readonly comparison shows navigation controls");
    const before = view.merge.b.state.doc.toString();
    await click(view, 1);
    check(view.merge.b.state.doc.toString() === before && view.merge.a.state.readOnly, "staged navigation preserves readonly documents");
    view.unified = true; await view.render();
    check(controls(view).length === 0, "patch-only unified preview hides unavailable native navigation");
    await leaf.detach(); leaf = null;
    const fs = require("node:fs/promises"), os = require("node:os"), path = require("node:path");
    const exec = require("node:util").promisify(require("node:child_process").execFile);
    root = await fs.mkdtemp(path.join(os.tmpdir(), "vaultbranch-nav-history-"));
    if (p.refreshTask) await p.refreshTask;
    p.refreshSoon?.cancel();
    original = { git: p.git, ready: p.ready, status: p.status, lastAutoRefresh: p.lastAutoRefresh };
    p.lastAutoRefresh = Date.now() + 3600000;
    const git = async (...args) => (await exec(original.git.binary, args, { cwd: root, windowsHide: true })).stdout;
    await git("init", "-b", "main"); await git("config", "user.name", "UI Test"); await git("config", "user.email", "test@example.invalid"); await git("config", "core.autocrlf", "false");
    await fs.writeFile(path.join(root, "history.md"), base); await git("add", "."); await git("commit", "-m", "base");
    await fs.writeFile(path.join(root, "history.md"), edited); await git("commit", "-am", "three changes");
    p.git = new original.git.constructor(root, { binary: original.git.binary }); await p.git.init(); p.ready = true;
    historyLeaf = await p.openFileHistory("history.md");
    const h = historyLeaf.view;
    check(controls(h).length === 2 && h.merge.chunks.length === 3, "file history shows two navigation controls");
    await click(h, 1); await click(h, 1);
    check(h.merge.b.state.selection.main.head === h.merge.chunks[1].fromB && h.merge.b.state.readOnly, "file history uses native chunk navigation in readonly pane");
    await p.updateSetting("showDiffNavigation", false);
    check(controls(h).length === 0, "setting immediately hides controls in open file history");
    await p.updateSetting("showDiffNavigation", true);
    await h.selectCommit(h.commits.at(-1));
    check(controls(h).length === 2, "selecting another commit replaces navigation without duplicate controls");
    await historyLeaf.detach(); historyLeaf = null;
    p.git = original.git; p.ready = original.ready; p.status = original.status; p.lastAutoRefresh = original.lastAutoRefresh; original = null;
    const tab = app.setting.pluginTabs.find(tab => tab.plugin === p || tab.id === "vaultbranch");
    const originalEl = tab.containerEl, originalTab = tab.activeTab;
    const settingsRoot = document.createElement("div"); document.body.appendChild(settingsRoot);
    try {
      tab.containerEl = settingsRoot; tab.activeTab = "other"; tab.display();
      const setting = [...settingsRoot.querySelectorAll(".setting-item")].find(item => /Show diff navigation buttons/.test(item.textContent));
      check(setting?.querySelector(".checkbox-container.is-enabled"), "Other settings exposes the enabled navigation toggle");
      setting.querySelector(".checkbox-container").click(); await pause(150);
      check(p.settings.showDiffNavigation === false, "native Setting toggle persists preference");
    } finally { tab.containerEl = originalEl; tab.activeTab = originalTab; settingsRoot.remove(); }
    check(errors.length === 0, "no runtime errors");
    return { results, errors };
  } finally {
    if (leaf) { await leaf.view.session?.reload(); await leaf.detach(); }
    await historyLeaf?.detach();
    if (original) { p.git = original.git; p.ready = original.ready; p.status = original.status; p.lastAutoRefresh = original.lastAutoRefresh; }
    if (staged) await p.git.run(["rm", "--cached", "-f", "--", name]);
    if (app.vault.getAbstractFileByPath(name)) await app.vault.trash(file, false);
    for (const [key, value] of [["diffAutosave", saved.autosave], ["collapseUnchanged", saved.collapse], ["showDiffNavigation", saved.navigation], ["language", saved.language]]) await p.updateSetting(key, value);
    if (root) await require("node:fs/promises").rm(root, { recursive: true, force: true });
    p.scheduleRefresh = scheduleRefresh; p.lastAutoRefresh = lastAutoRefresh;
    await p.refresh();
    window.removeEventListener("error", onError); window.removeEventListener("unhandledrejection", onError);
  }
})()
